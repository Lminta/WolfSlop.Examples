import assert from "node:assert/strict";
import { checkGrid, checkDefinition, flood, resizeGrid, line, usedObjects, objectUsage, removeObject, canvasRasterSize } from "../WolfNET.Editor/wwwroot/editor-model.js";

const passage = { type: "passage", id: 0, collides: false, raycastTransparent: true };
const wall = { type: "wall", id: 1, passageId: 0, collides: true, raycastTransparent: false };
const sprite = { type: "sprite", id: 2, passageId: 0, textureLayer: 8, collides: false, raycastTransparent: true };
const atlasSprite = { ...sprite, atlas: { directions: 2, frames: [{x:0,y:0,width:16,height:8}, {x:16,y:0,width:16,height:8}] }, rotationDegrees: 90 };
assert.equal(checkDefinition(atlasSprite, {0:passage}), atlasSprite);
for(const facingCamera of [true,false])assert.equal(checkDefinition({...atlasSprite,facingCamera},{0:passage}).facingCamera,facingCamera);
for(const facingCamera of [null,"false",0,1,{}])assert.throws(()=>checkDefinition({...atlasSprite,facingCamera},{0:passage}));
assert.equal(checkDefinition({...sprite, planeAxis: "x"}, {0: passage}).planeAxis, "x");
assert.throws(() => checkDefinition({...sprite, planeAxis: "z"}, {0: passage}));
assert.throws(() => checkDefinition({...atlasSprite, planeAxis: "y"}, {0: passage}));
for (const atlas of [{frames:[]}, {...atlasSprite.atlas,directions:3}, {frames:[{x:-1,y:0,width:1,height:1}]}, {frames:[{x:0,y:0,width:0,height:1}]}])
    assert.throws(() => checkDefinition({...atlasSprite,atlas}, {0:passage}));
assert.throws(() => checkDefinition({...atlasSprite,textureLayer:255}, {0:passage}));
assert.throws(() => checkDefinition({...atlasSprite,rotationDegrees:Infinity}, {0:passage}));
const door={type:"door",id:4,passageId:0,collides:true,raycastTransparent:true,texture:"textures/doors/glass-door.png",axis:"x",openSeconds:.8};
assert.equal(checkDefinition(door,{0:passage}),door);
assert.throws(()=>checkDefinition({...door,axis:"z"},{0:passage}));
for(const openSeconds of [0,-1,NaN,Infinity])assert.throws(()=>checkDefinition({...door,openSeconds},{0:passage}));
for(const autoCloseSeconds of [0,-1,10])assert.equal(checkDefinition({...door,autoCloseSeconds},{0:passage}).autoCloseSeconds,autoCloseSeconds);
for(const autoCloseSeconds of [NaN,Infinity,-Infinity,"10"])assert.throws(()=>checkDefinition({...door,autoCloseSeconds},{0:passage}));
assert.throws(()=>checkDefinition({...door,texture:42},{0:passage}));
const group = { type: "spriteGroup", id: 3, passageId: 0, sprites: [{ spriteId: 2, offset: { x: -.25, y: .5 } }], collides: false, raycastTransparent: true };
const objects = { 0: passage, 1: wall, 2: sprite, 3: group };
const scaledGroup = { ...group, sprites: [{ spriteId: 2, offset: { x: 0, y: 0, z: -.25 }, scale: { x: .5, y: 2 } }] };
assert.equal(checkDefinition(scaledGroup, objects), scaledGroup);
assert.throws(() => checkDefinition({ ...scaledGroup, sprites: [{ ...scaledGroup.sprites[0], scale: { x: -1, y: 1 } }] }, objects));
assert.throws(() => checkDefinition({ ...scaledGroup, sprites: [{ ...scaledGroup.sprites[0], scale: null }] }, objects));
assert.throws(() => checkDefinition({ ...scaledGroup, sprites: [{ ...scaledGroup.sprites[0], scale: 2 }] }, objects));
assert.throws(() => checkDefinition({ ...scaledGroup, sprites: [{ ...scaledGroup.sprites[0], offset: { x: 0, y: 0, z: Infinity } }] }, objects));
const grid = resizeGrid([], 5, 5, 0, 1);
assert.equal(grid[0][0], 1);
assert.equal(grid[2][2], 0);
assert.equal(grid[4][2], 1);
grid[2][2] = 3;
const grown = resizeGrid(grid, 7, 6, 0, 1);
assert.equal(grown[2][2], 3, "Resizing must preserve existing interior cells");
assert.equal(grown[4][2], 0, "Old boundary must become floor when expanding");
assert.equal(grown[6][4], 1);
const shrunk = resizeGrid(grown, 3, 3, 0, 1);
assert.equal(shrunk[2][2], 1);
const expandedCircuit = resizeGrid(grid, 256, 512, 0, 1);
assert.equal(expandedCircuit.length, 256);
assert.equal(expandedCircuit[0].length, 512);
assert.equal(expandedCircuit[2][2], 3);
assert.equal(expandedCircuit[255][510], 1);
assert.throws(() => resizeGrid(grid, 513, 3, 0, 1));
assert.throws(() => resizeGrid(grid, 3, 513, 0, 1));
assert.equal(flood(grid, 1, 1, 2), true);
assert.equal(grid[3][3], 2);
assert.equal(grid[2][2], 3);
assert.equal(grid[0][0], 1);
assert.equal(flood(grid, 1, 1, 2), false);
const isolated = [[0, 1, 0], [1, 1, 1], [0, 1, 0]];
flood(isolated, 0, 0, 3);
assert.equal(isolated[2][0], 0, "Fill must not jump disconnected areas");
const visited = [];
line(0, 0, 4, 2, (x, y) => visited.push([x, y]));
assert.deepEqual(visited, [[0, 0], [1, 1], [2, 1], [3, 2], [4, 2]]);
const reverse = [];
line(4, 2, 0, 0, (x, y) => reverse.push([x, y]));
assert.deepEqual(reverse[0], [4, 2]);
assert.deepEqual(reverse.at(-1), [0, 0]);
const map = { worldMap: grid, playerStart: { x: 1.5, y: 1.5, directionX: -1, directionY: 0, moveSpeed: 5, rotSpeed: 3 } };
assert.equal(checkGrid(map), map);
assert.equal(checkGrid({ ...map, worldMap: expandedCircuit }).worldMap, expandedCircuit);
assert.throws(() => checkGrid({ ...map, worldMap: Array.from({ length: 513 }, () => [1, 0, 1]) }));
assert.equal(checkDefinition({ ...wall, jumpable: true }, objects).jumpable, true);
assert.equal(checkDefinition({ ...wall, crouchable: true }, objects).crouchable, true);
assert.throws(() => checkDefinition({ ...wall, crouchable: "true" }, objects));
for(const crouchDrop of [0,-1,.5,NaN,Infinity])assert.throws(()=>checkGrid({...map,playerStart:{...map.playerStart,crouchDrop}}));
for(const crouchSpeedMultiplier of [0,-1,NaN,Infinity])assert.throws(()=>checkGrid({...map,playerStart:{...map.playerStart,crouchSpeedMultiplier}}));
assert.throws(() => checkDefinition({ ...wall, jumpable: "true" }, objects));
assert.equal(checkGrid({ ...map, playerStart: { ...map.playerStart, jumpRise: 0.25, jumpLength: 2, jumpSpeedMultiplier: 1.25 } }).playerStart.jumpLength, 2);
for (const jumpRise of [-1, 0.5, NaN, Infinity]) assert.throws(() => checkGrid({ ...map, playerStart: { ...map.playerStart, jumpRise } }));
for (const jumpLength of [-1, 65, NaN, Infinity]) assert.throws(() => checkGrid({ ...map, playerStart: { ...map.playerStart, jumpLength } }));
for (const jumpSpeedMultiplier of [0, -1, NaN, Infinity]) assert.throws(() => checkGrid({ ...map, playerStart: { ...map.playerStart, jumpSpeedMultiplier } }));
assert.equal(checkGrid({ ...map, sky: { texture: "textures/skyboxes/skybox.jpg", rotationDegrees: 90 } }).sky.rotationDegrees, 90);
assert.throws(() => checkGrid({ ...map, sky: { texture: "", rotationDegrees: 0 } }));
assert.throws(() => checkGrid({ ...map, sky: { texture: "sky.jpg", rotationDegrees: Infinity } }));
assert.equal(checkDefinition({ ...passage, ceilingMode: "sky" }, objects).ceilingMode, "sky");
assert.throws(() => checkDefinition({ ...passage, ceilingMode: "unknown" }, objects));
for (const surface of ["asphalt", "mud", "grass"])
    assert.equal(checkDefinition({ ...passage, surface }, objects).surface, surface);
for (const surface of [null, "sand", "Asphalt", 1])
    assert.throws(() => checkDefinition({ ...passage, surface }, objects));
for (const controller of ["player", "car"])
    assert.equal(checkGrid({ ...map, playerStart: { ...map.playerStart, controller } }).playerStart.controller, controller);
for (const controller of [null, "truck", "Car", 1])
    assert.throws(() => checkGrid({ ...map, playerStart: { ...map.playerStart, controller } }));
assert.equal(checkGrid({ ...map, playerStart: { ...map.playerStart, collisionRadius: 0.15 } }).playerStart.collisionRadius, 0.15);
for (const collisionRadius of [0, -1, 0.5, NaN, Infinity])
    assert.throws(() => checkGrid({ ...map, playerStart: { ...map.playerStart, collisionRadius } }));
assert.deepEqual(Object.keys(usedObjects({ map, objects })), ["0", "1", "2", "3"]);
assert.throws(() => usedObjects({ map, objects: { 0: passage, 1: wall, 3: group } }));
assert.throws(() => checkGrid({ ...map, worldMap: [[0], [0, 0]] }));
assert.throws(() => checkDefinition({ ...wall, floorTexture: "textures/wolf/wood.png" }, objects));
assert.throws(() => checkDefinition({ ...wall, passageId: 2 }, objects));
assert.throws(() => checkDefinition({ ...sprite, textureLayer: 256 }, objects));
assert.throws(() => checkDefinition({ ...group, sprites: [{ spriteId: 1, offset: { x: 0, y: 0 } }] }, objects));
const deletion = { map: { ...structuredClone(map), objects: { 0: "passage.json", 1: "wall.json", 2: "sprite.json", 3: "group.json" } }, objects: structuredClone(objects) };
deletion.objects[4] = { ...passage, id: 4 };
deletion.objects[5] = { ...sprite, id: 5 };
const beforeDelete = structuredClone(deletion);
assert.ok(objectUsage(deletion, 0).passages > 0);
assert.throws(() => removeObject(deletion, 0, 1));
assert.deepEqual(deletion, beforeDelete, "Rejected deletion must not mutate the document");
removeObject(deletion, 0, 4);
assert.equal(deletion.objects[1].passageId, 4);
assert.equal(deletion.objects[2].passageId, 4);
assert.equal(deletion.objects[3].passageId, 4);
assert.equal(deletion.objects[0], undefined);
assert.equal(deletion.map.objects[0], undefined);
removeObject(deletion, 2, 5);
assert.equal(deletion.objects[3].sprites[0].spriteId, 5);
assert.equal(deletion.map.worldMap[1][1], 5);
assert.deepEqual(deletion.objects[3].sprites[0].offset, { x: -.25, y: .5 });
assert.deepEqual(deletion.deletedObjectIds, [0, 2]);
removeObject(deletion, 3, 4);
assert.equal(deletion.map.worldMap[2][2], 4);
deletion.objects[9] = { ...passage, id: 9 };
removeObject(deletion, 9);
assert.equal(deletion.objects[9], undefined);
assert.deepEqual(Object.keys(usedObjects(deletion)), ["1", "4", "5"]);
for (const zoom of [8, 80]) for (const dpr of [1, 2]) {
    const raster = canvasRasterSize(256 * zoom, 512 * zoom, dpr);
    assert(raster.width <= 8192 && raster.height <= 8192, "Large maps must keep both canvas sides within the raster limit");
    assert(raster.width * raster.height <= 16_777_216, "Large maps must keep canvas pixels within the allocation budget");
    assert.equal(raster.height, raster.width * 2, "Raster limiting must preserve the map's proportions");
}
assert.deepEqual(canvasRasterSize(256 * 8, 512 * 8, 1), { width: 2048, height: 4096 });
assert.deepEqual(canvasRasterSize(24 * 32, 24 * 32, 2), { width: 1536, height: 1536 }, "Small map raster density must stay unchanged");
assert.deepEqual(canvasRasterSize(99, 75, 1.25), { width: 124, height: 94 }, "Uncapped canvas dimensions must retain their original rounding");
assert.equal(canvasRasterSize(100, 20_000, 2).height, 8192, "Narrow maps must also respect the side limit");
console.log("PASS: editor grid, fill, strokes, dependencies, schema, object deletion, and bounded canvas allocation.");
